'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const {once}=require('node:events');
const {DatabaseSync}=require('node:sqlite');
const {createServer}=require('../server/server.cjs');
test('registration, login, session, logout, persistence, access control',async t=>{
  const dir=fs.mkdtempSync(path.join(os.tmpdir(),'feed-days-'));
  const dbPath=path.join(dir,'test.sqlite');
  let server;
  t.after(async()=>{if(server?.listening)await new Promise(resolve=>server.close(resolve));fs.rmSync(dir,{recursive:true,force:true});});
  async function start(){server=createServer({dbPath,production:false});server.listen(0,'127.0.0.1');await once(server,'listening');return 'http://127.0.0.1:'+server.address().port;}
  let base=await start();
  const req=(p,options={})=>fetch(base+p,{redirect:'manual',...options});
  const post=(p,body,cookie,origin=base)=>req('/api/auth/'+p,{method:'POST',headers:{'Content-Type':'application/json',Origin:origin,...(cookie?{Cookie:cookie}:{})},body:JSON.stringify(body)});
  const credentials={id:'Player_01',password:'Test-password-123'};
  assert.equal((await req('/game')).status,303);
  assert.equal((await req('/api/auth/me')).status,401);
  assert.equal((await post('register',{id:'a',password:'short'})).status,400);
  assert.equal((await post('register',credentials,undefined,'https://other.example')).status,403);
  assert.equal((await post('register',credentials)).status,201);
  assert.equal((await post('register',{...credentials,id:'player_01'})).status,409);
  assert.equal((await post('login',{...credentials,password:'wrong-password'})).status,401);
  let r=await post('login',credentials);assert.equal(r.status,200);
  const rawCookie=r.headers.get('set-cookie');assert.match(rawCookie,/HttpOnly/);assert.match(rawCookie,/SameSite=Lax/);
  const cookie=rawCookie.split(';')[0];
  r=await req('/api/auth/me',{headers:{Cookie:cookie}});assert.equal((await r.json()).id,'Player_01');
  assert.equal((await req('/game',{headers:{Cookie:cookie}})).status,200);
  assert.equal((await req('/game.html')).status,303);
  assert.equal((await req('/server/server.cjs')).status,404);
  assert.equal((await req('/data/feed-days.sqlite')).status,404);
  await new Promise(resolve=>server.close(resolve));
  const db=new DatabaseSync(dbPath);const row=db.prepare('SELECT salt,password_hash FROM accounts').get();assert.equal(row.salt.length,32);assert.equal(row.password_hash.length,128);assert.notEqual(row.password_hash,credentials.password);
  assert.notEqual(db.prepare('SELECT token_hash FROM sessions').get().token_hash,cookie.split('=')[1]);db.close();
  base=await start();
  assert.equal((await req('/api/auth/me',{headers:{Cookie:cookie}})).status,200);
  assert.equal((await post('logout',{},cookie)).status,200);
  assert.equal((await req('/api/auth/me',{headers:{Cookie:cookie}})).status,401);
  assert.equal((await post('login',credentials)).status,200);
});
